"""Generate docs/PERFORMANCE.md from results/scaling_profile.json (no hand typed numbers)."""

from __future__ import annotations

import json
import math
from pathlib import Path


def slope(xs, ys):
    pts = [(math.log(x), math.log(y)) for x, y in zip(xs, ys) if y and y > 0]
    if len(pts) < 2:
        return float("nan")
    (x0, y0), (x1, y1) = pts[0], pts[-1]
    return (y1 - y0) / (x1 - x0)


def main():
    d = json.loads(Path("results/scaling_profile.json").read_text())
    rows = [r for r in d["rows"] if not r.get("failed")]
    big = [r for r in rows if r["n"] >= 500]
    out = ["# Performance and scaling (generated)", "",
           "Generated by `scripts/make_perf_doc.py` from `results/scaling_profile.json`",
           "(produced by `scripts/profile_scale.py`, fixed seeds, one process per size). Wall times are",
           "machine dependent (this run: 2 shared CPUs, no GPU). The study shows are computational",
           "scaling cases with relaxed altitude and geofence limits so every size is a valid show; they",
           "say nothing about an operational envelope.", "",
           "| n | targets (s) | Hungarian, one transition (s) | plan total (s) | exact verify (s) | "
           "piece pairs solved | peak RSS (MB) | verified |", "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        out.append(f"| {r['n']} | {r['targets_s']:.2f} | {r['hungarian_one_transition_s']:.2f} | "
                   f"{r['plan_total_s']:.2f} | {r['verify_s']:.2f} | {r['pairs_checked']} | "
                   f"{r['peak_rss_mb']:.0f} | {r['verified_ok']} |")
    ns = [r["n"] for r in big]
    out += ["", "## Empirical scaling exponents (log log slope between the first and last size "
            f"with n >= 500, n = {ns[0]} to {ns[-1]})", "",
            f"- Hungarian assignment (one transition): n^{slope(ns, [r['hungarian_one_transition_s'] for r in big]):.2f}",
            f"- Planner total: n^{slope(ns, [r['plan_total_s'] for r in big]):.2f}",
            f"- Exact verification: n^{slope(ns, [r['verify_s'] for r in big]):.2f}",
            f"- Piece pairs solved: n^{slope(ns, [r['pairs_checked'] for r in big]):.2f}",
            f"- Peak memory: n^{slope(ns, [r['peak_rss_mb'] for r in big]):.2f}", ""]
    last = rows[-1]
    out += [f"## Where the time goes at n = {last['n']} (cProfile, cumulative seconds)", "",
            "| function | cumulative (s) |", "|---|---|"]
    for t in last["verify_top_cumulative"]:
        out.append(f"| `{t['fn']}` | {t['cum_s']} |")
    out += ["", "## Reading this honestly", "",
            "- Planning is dominated by the O(n^3) Hungarian assignment (scipy `linear_sum_assignment`) at "
            "large n. Replacing it by a sparse or nearest neighbour assignment would change plans and was "
            "not done.",
            "- Verification is dominated by companion matrix eigenvalue solves for piece pairs whose "
            "whole leg boxes overlap. The number of such pairs grows close to quadratically because long "
            "synchronous legs have boxes that span much of the formation.",
            "- A time splitting prefilter (cut long pieces into short sub-pieces so boxes stay small) was "
            "tried. It reproduced the same minimum separation to about 1e-13 m but was slower in a quick "
            "local trial because the per piece Python loop in candidate generation grew, so it was "
            "discarded and no result file was kept for it. A vectorised candidate search is the open "
            "next step.",
            "- A fix that changed correctness behaviour was made earlier: a local refinement at multiple "
            "roots (`docs/VERIFIER.md`), which does not change scaling.",
            "- Memory is not the limit at these sizes for the verifier. The Monte Carlo stress simulator "
            "was measured separately (`results/stress_scaling.json`, per trial CPU time).", ""]
    Path("docs/PERFORMANCE.md").write_text("\n".join(out))


if __name__ == "__main__":
    main()
