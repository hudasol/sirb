"""Write the phase 6 section of docs/MUTATION.md from results/mutation.json (section ``phase6``).

Every survivor gets a class and a reason: the automatic classes of scripts/mutation_summary.py,
then the hand written arguments in scripts/survivor_reasons_phase6.json (verify.py, assign.py and
planner survivors) and in results/mutation_phase6_triage.json (verify2.py). A survivor without an
argument stays ``open`` and is listed by name.

    python scripts/make_mutation_phase6_doc.py
"""

from __future__ import annotations

import collections
import json
import re
from pathlib import Path

DOC = Path("docs/MUTATION.md")
START, END = "<!-- PHASE6:START -->", "<!-- PHASE6:END -->"


def key(fn: str, mutant: str) -> str:
    func, num = mutant.rsplit(".x_", 1)[1].rsplit("__mutmut_", 1)
    return f"{fn}:{func}:{num}"


def main() -> None:
    m = json.loads(Path("results/mutation.json").read_text())
    p6, p5 = m["phase6"], m.get("after", {})
    rules = json.loads(Path("scripts/survivor_reasons_phase6.json").read_text())["rules"]
    tri = {e["mutant"]: e["final"] for e in json.loads(
        Path("results/mutation_phase6_triage.json").read_text())["entries"]
        if isinstance(e.get("final"), dict)}
    L = [START, "", "## Phase 6: fresh mutmut run on the current code", "",
         "Generated by `scripts/make_mutation_phase6_doc.py` from the `phase6` section of "
         "`results/mutation.json` (mutmut 3.8.0 on Linux, 4 workers, the test selection of "
         "`pyproject.toml` including the phase 6 killer tests). The phase 5 tables above are kept "
         "for history; the scores below are the current ones.", "",
         "| File | Mutants | Killed | Survived | Timeout | Not checked | Score | Phase 5 score |",
         "|---|---|---|---|---|---|---|---|"]
    for fn, d in sorted(p6.items()):
        old = p5.get(fn, {}).get("score")
        L.append(f"| `{fn}` | {d['total']} | {d['killed']} | {d['survived']} | {d['timeout']} | "
                 f"{d['not_checked']} | {100 * d['score']:.1f}% | "
                 + (f"{100 * old:.1f}% |" if old is not None else "|"))
    rows, classes = [], collections.defaultdict(collections.Counter)
    for fn, d in sorted(p6.items()):
        for s in d.get("survivors", []):
            cls, why = s["class"], s["reason"]
            k = key(fn, s["mutant"])
            if cls == "open":
                if k in rules:
                    cls, why = rules[k]
                elif fn == "sirb/verify2.py" and s["mutant"] in tri:
                    cls, why = tri[s["mutant"]]["class"], tri[s["mutant"]]["reason"]
            classes[fn][cls] += 1
            rows.append((fn, s["mutant"].rsplit(".x_", 1)[1], cls, why, s["change"], k))
    names = sorted({c for v in classes.values() for c in v})
    L += ["", "Survivors by class after the arguments (classes as defined above; "
          "`equivalent_result_slower` is a verify2 mutant that only slows the search):", "",
          "| File | " + " | ".join(names) + " |", "|---|" + "---|" * len(names)]
    for fn in sorted(classes):
        L.append(f"| `{fn}` | " + " | ".join(str(classes[fn][c]) for c in names) + " |")
    still = [r for r in rows if r[2] == "open"]
    L += ["", f"Survivors still without an argument: {len(still)}."]
    if still:
        L += ["", "| File | Mutant | Change |", "|---|---|---|"]
        L += [f"| `{r[0]}` | `{r[1]}` | {r[4][:140].replace('|', '/')} |" for r in still]
    argued = [r for r in rows if r[5] in rules]
    if argued:
        L += ["", "Hand written phase 6 arguments for survivors that the automatic rules left open "
              "(`scripts/survivor_reasons_phase6.json`):", "",
              "| File | Mutant | Class | Reason |", "|---|---|---|---|"]
        L += [f"| `{r[0]}` | `{r[1]}` | {r[2]} | {r[3]} |" for r in argued]
    L += ["", "Phase 5 labels that the phase 6 triage showed to be wrong (the mutants are now "
          "killed) are listed with their tests in `results/mutation_phase6_triage.json`; the "
          "remaining labels are arguments, not proofs. One real defect was found while killing "
          "survivors: the baseline planner emitted zero length holds when nobody moved in a "
          "transition (fixed, with a regression test).", "", END]
    text = DOC.read_text(encoding="utf-8")
    block = "\n".join(L)
    if START in text:
        text = re.sub(re.escape(START) + ".*?" + re.escape(END), lambda _: block, text, flags=re.S)
    else:
        text = text.rstrip("\n") + "\n\n" + block + "\n"
    DOC.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
