"""Generate docs/OVERNIGHT_REPORT.md (phase 6). Narrative is fixed text; every number is read from
results/*.json, viewer/data/index.json or docs/PREDICTIONS.md. A section whose result file does not
exist yet says so instead of quoting a number.

    python scripts/make_overnight_report.py
"""

from __future__ import annotations

import json
import re
from pathlib import Path


def load(p):
    p = Path(p)
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def f(x, n=3):
    return "n/a" if x is None else f"{x:.{n}f}"


def prediction(num: str) -> str:
    text = Path("docs/PREDICTIONS.md").read_text(encoding="utf-8")
    m = re.search(rf"^\| {num} \|.*\| ([^|]*) \|\s*$", text, re.M)
    return m.group(1).strip() if m else "not found"


def main() -> None:
    idx = load("viewer/data/index.json")
    gd = load("results/gnss_faa_derivation.json")
    s0, s1 = load("results/sensitivity.json"), load("results/sensitivity_faa.json")
    mg = load("results/margin.json")
    gr = load("results/ground_robots.json")
    vs = load("results/verify_speed.json")
    tri = load("results/mutation_phase6_triage.json")
    L = ["# Overnight report, phase 6", "",
         "Generated by `scripts/make_overnight_report.py`; numbers are read from result files. Branch "
         "`phase6`, pull request into `phase5-hardening` (hudasol/sirb#2). **Nothing is merged and no "
         "tag exists.** Simulation and planning only; not flight certified.", "",
         "## Working conditions (affects what was finished)", "",
         "The work ran on the owner's Windows machine, not the 2 core container described in the "
         "brief. mutmut and the forked Monte Carlo workers need Linux, so they ran under WSL. The "
         "machine was shared with another project's training jobs, and it was suspended for about "
         "three hours in the middle of the night (the WSL clock advanced 18 minutes while the wall "
         "clock advanced about 3 hours 20 minutes). Later in the morning WSL itself stopped "
         "responding (service timeout); it was not restarted, because that would also have killed "
         "the other project's jobs. The sourced sensitivity run and the margin study were "
         "interrupted with part of their units cached in the WSL clone `~/sirb-run/results/.cache`; "
         "relaunching the chain resumes them. Long runs therefore finished late or not at all; "
         "each item below says which.", "",
         "## Per stream", "",
         "### A. Evidence debt (mutation survivors)", "",
         "mutmut does not run on native Windows. Under WSL its single threaded baseline phase did not "
         "finish in 40 minutes under the shared load and would have needed hours more, so I stopped "
         "it and replaced it with a manual check: each recorded survivor's one line change is applied "
         "to a copy of the package and the selected tests are run against it "
         "(`scripts/check_survivors.py`, if present)."]
    if tri:
        L += ["", "| File | Result of the manual check | Survivors |", "|---|---|---|"]
        for k, v in sorted(tri["summary"].items()):
            fn, cls = k.split("|")
            L.append(f"| `{fn}` | {cls} | {v} |")
        L += ["", "Only `verify2.py` and `assign.py` went through every stage (old selection, new "
              "killer tests, slow tests). For `verify.py` and the planners only the slow tests were "
              "tried, for part of the survivors; `open` there means it survived the slow tests and has "
              "no argument, `not_checked` means it was never run (`coverage` in the file). New mutmut "
              "scores were not produced; `docs/MUTATION.md` keeps the phase 5 tables."]
    else:
        L.append("**Not finished**: the triage was still running when this report was generated; "
                 "`results/mutation.json` and the scores in `docs/MUTATION.md` are unchanged from "
                 "phase 5.")
    L += [f"Prediction P10: {prediction('P10')}.", "",
          "### B. Real GNSS parameters", ""]
    if gd:
        st = gd["statistics"]
        L.append(f"Source found and cited: {gd['source']['source_name']} (US government work). From "
                 f"{st['n_sites']} sites, median 95% horizontal error {f(st['h95_median_m'])} m gives a "
                 f"per axis sigma of {f(st['bias_sigma_median_m'])} m (site range "
                 f"{f(st['bias_sigma_min_site_m'])} to {f(st['bias_sigma_max_site_m'])} m), written to "
                 "`shows/gnss_faa_sps_standalone.json`. **Every value stays `assumed: true`**: the "
                 "source gives the absolute error of one standalone receiver, while the model needs "
                 "the relative error between drones, for which no public source was found. "
                 "marsad and Tashwish publish nothing usable and were not used or modified.")
    if s0 and s1:
        for k in s1["oat"]:
            L.append(f"* {k}: P(violation) {f(s0['oat'][k]['baseline']['p'])} assumed, "
                     f"{f(s1['oat'][k]['baseline']['p'])} sourced (`docs/GNSS_SOURCED.md`).")
    else:
        L.append("**Sensitivity rerun with the sourced value not finished** when this report was "
                 "generated (`results/sensitivity_faa.json` missing).")
    L += [f"Prediction P15: {prediction('P15')}.", "",
          "### C. Margin synthesis", "",
          "`sirb/margin.py` and `python -m sirb margin` (planning aid, model dependence stated in "
          "every output), with unit tests including a real small run and a CLI test. The tests found "
          "and fixed a bug before any study ran: stages that share one shape object were scaled twice."]
    if mg:
        for r in mg["rows"]:
            L.append(f"* {r['case']}: {r['status']}, required nominal minimum separation "
                     f"{f(r['required_nominal_min_separation_m'])} m.")
    else:
        L.append("**Study not finished** when this report was generated (`results/margin.json` "
                 "missing).")
    L += [f"Prediction P11: {prediction('P11')}.", "",
          "### D. Verifier speed", ""]
    if vs:
        L += ["Vectorised `_candidate_pairs` (dense tiles with an exact x axis reject), the loop kept "
              "as a test reference. Equality: identical arrays (values, order, dtype) on the 10,856 "
              "differential fleets and on every benchmark fleet; `tests/test_verify_candidates.py`. "
              f"Benchmark (`results/verify_speed.json`, {vs['machine'].get('platform', '')}, a "
              "saturated machine, so times are noisy; verify timed once):", "",
              "| n | candidate search old (s) | new (s) | speedup | verify old (s) | new (s) | speedup "
              "| identical |", "|---|---|---|---|---|---|---|---|"]
        for r in vs["rows"]:
            c, v = r["prefilter"], r["verify"]
            L.append(f"| {r['n']} | {f(c['old_s'])} | {f(c['new_s'])} | {f(c['speedup'], 2)} | "
                     f"{f(v['old_s'], 1)} | {f(v['new_s'], 1)} | {f(v['speedup'], 2)} | "
                     f"{c['identical'] and v['reports_equal']} |")
        L += ["", "The candidate search was only a few percent of verification time, so the total "
              "gain is small, as predicted. A full rerun of `scripts/differential_report.py` on "
              "Windows gave the same output with the old and the new search, but both differed from "
              "the committed `results/differential.json` in the degenerate collision family (one "
              "disagreement record fewer, one verdict moved between FAIL and UNDECIDED, largest exact "
              "minus lower bound larger), with Python 3.13.0 here against 3.13.16 for the committed "
              "file. That is an environment dependence of the near degenerate cases, not a change "
              "from stream D; the committed file was not overwritten."]
    else:
        L.append("**Not integrated**: the vectorised candidate search was delegated and was not "
                 "merged into this branch when this report was generated; `sirb/verify.py` is "
                 "unchanged.")
    L += [f"Prediction P12: {prediction('P12')}.", "",
          "### E. Reproducibility (Hungarian ties)", "",
          "Done and verified on CI. Two causes, not one: last bit noise in the targets (CPU dependent "
          "trigonometry and matrix kernels) and tied assignments that flip when costs differ in the "
          "last bit. Fix: snap targets to a 2^-20 m grid, exact integer assignment costs, no BLAS or "
          "pow in leg construction (`docs/REPRODUCIBILITY.md`). The CI check against the committed "
          "copy is now hard. Every result derived from planned fleets changes (`docs/CHANGES.md`)."]
    if idx:
        L.append("Fleet hashes now committed: " + ", ".join(
            f"`{s['id']}` `{s['fleet_sha256'][:8]}`" for s in idx["shows"]) + ".")
    L += [f"Prediction P13: {prediction('P13')}.", "",
          "### F. Ground robots (exploratory)", ""]
    if gr:
        rows = [r for r in gr["rows"] if r["planner"] == "grid"]
        ok = sum(1 for r in rows if r.get("verified_ok"))
        L.append(f"Grid planner (`sirb/planner/grid.py`): verified plans in {ok} of {len(rows)} "
                 "tasks (`docs/GROUND_ROBOTS.md`). The restart policy was tuned on these same tasks, "
                 "so this is a development result.")
    L += [f"Prediction P14: {prediction('P14')}.", "",
          "### G. Reviewer pack", "",
          "`scripts/make_briefs.py` generates `docs/BRIEF_TII_ATRC.md`, `docs/BRIEF_EDGE.md`, "
          "`docs/BRIEF_ADEO.md` and `docs/SUMMARY_AR.md` (Arabic, marked as needing native review) "
          "from result files. The briefs describe Sirb only; they make no claim about the "
          "organisations. ADEO's full name and remit could not be confirmed from a retrieved source, "
          "so the ADEO brief says so and asks the owner to confirm the framing.", "",
          "### H. Adversarial review", "",
          "Done as a hostile read of the phase 6 changes (the review skill was not run, for lack of "
          "time). Findings and what was done:", "",
          "1. Stale results next to changed code. Stream E changes every planned fleet, but the "
          "stress and sensitivity result files were not all regenerated (list in "
          "`docs/CHANGES.md`). Fixed in part (viewer data, planner benchmark); the rest is stated "
          "as stale in `docs/CHANGES.md` and below rather than hidden.",
          "2. A sourced number that does not measure what the model needs. The FAA figure is "
          "absolute error; the model needs relative error. Kept `assumed: true` and said so in the "
          "file, in `docs/GNSS_SOURCED.md` and in every brief.",
          "3. Encoding. `docs/GROUND_ROBOTS.md` was written in the Windows code page (a broken "
          "superscript). Fixed; other generators assume UTF-8 and must run with UTF-8 as default "
          "(Linux, or `PYTHONUTF8=1` on Windows).",
          "4. Development result presented as a measurement. The grid planner's restart policy was "
          "tuned on the reported tasks; stated in `docs/GROUND_ROBOTS.md` and P14.",
          "5. Organisation claims. The briefs were written to describe Sirb only; ADEO's remit was "
          "not verified and the brief says so. No partnership, endorsement or cost is claimed.",
          "6. Attribution. Earlier phases' commits carry co author trailers and session links; "
          "phase 6 commits do not. History was not rewritten (hard rule), so the old trailers "
          "remain.",
          "7. Test platform. Two tests fail on a Windows checkout only (`/dev/zero`, and CRLF "
          "conversion of the vendored three.js changing its hash); the Linux suite and CI are green.",
          ""]
    L += [
          "## What I did not get to", "",
          "* The full regeneration of the stress results after stream E (`results/stress_*.json`, "
          "`results/sensitivity.json`, `results/scaling_profile.json`) unless `docs/CHANGES.md` lists "
          "them as regenerated. Until then those files and the README headline lines derived from them "
          "come from the pre phase 6 code.",
          "* New mutmut scores; stream D integration (unless stated above).", "",
          "## Exact steps for Huda", "",
          "1. Read this report, `docs/CHANGES.md` and `docs/REPRODUCIBILITY.md`; review PR "
          "hudasol/sirb#2 (base `phase5-hardening`). Nothing is merged and no tag was pushed.",
          "2. On a Linux machine, finish the chain: `SIRB_WORKERS=8 nice -n 5 bash "
          "scripts/run_phase6_chain.sh /tmp/p6logs` (cached units resume), then run "
          "`python scripts/make_results_doc.py`, `python scripts/make_sensitivity_doc.py`, "
          "`python scripts/make_gnss_sourced_doc.py`, `python scripts/make_margin_doc.py`, "
          "`python scripts/make_briefs.py` and `python scripts/make_overnight_report.py`, and commit.",
          "3. Confirm the ADEO framing and the audience questions in the three briefs; have the "
          "Arabic summary reviewed by a native speaker.",
          "4. Decide whether the FAA derived file should mark `bias_sigma` as sourced; this report "
          "keeps it assumed because the source measures absolute, not relative, error.",
          "5. Merge PR #1 and then PR #2 only after review; create tags yourself if wanted.", ""]
    Path("docs/OVERNIGHT_REPORT.md").write_text("\n".join(L) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
