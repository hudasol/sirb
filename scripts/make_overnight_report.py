"""Generate docs/OVERNIGHT_REPORT.md (phase 6). Narrative is fixed text; every number is read from
results/*.json, viewer/data/index.json, docs/CHANGES.md or docs/PREDICTIONS.md. A section whose
result file does not exist yet says so instead of quoting a number.

    python scripts/make_overnight_report.py
"""

from __future__ import annotations

import json
import re
from pathlib import Path


def load(p):
    p = Path(p)
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def f(x, n=3):
    return "n/a" if x is None else f"{x:.{n}f}"


def prediction(num: str) -> str:
    text = Path("docs/PREDICTIONS.md").read_text(encoding="utf-8")
    m = re.search(rf"^\| {num} \|.*\| ([^|]*) \|\s*$", text, re.M)
    return m.group(1).strip() if m else "not found"


def stale_files() -> str:
    t = Path("docs/CHANGES.md").read_text(encoding="utf-8")
    m = re.search(r"^Stale files[^:]*: (.*)$", t, re.M)
    return m.group(1).strip() if m else "not found"


def main() -> None:
    mg, ck = load("results/margin.json"), load("results/margin_cli_check.json")
    s0, s1 = load("results/sensitivity.json"), load("results/sensitivity_faa.json")
    rel = load("results/gnss_relative_derivation.json")
    mut = load("results/mutation.json")
    pp = load("results/platform_probe/linux_py31316_vs_windows_py3130.json")
    pl = load("results/platform_probe/linux_py31316_vs_linux_py3130.json")
    dcmp = load("results/differential_linux_vs_committed.json")
    idx = load("viewer/data/index.json")
    L = ["# Overnight report, phase 6", "",
         "Generated by `scripts/make_overnight_report.py`; numbers are read from result files. Branch "
         "`phase6`, pull request hudasol/sirb#2 into `phase5-hardening`; pull request hudasol/sirb#1 "
         "(`phase5-hardening` into `main`) is also open. **Nothing is merged and no tag exists.** "
         "Simulation and planning only; not flight certified.", "",
         "Phase 6 ran over two nights. The first night (streams A to H of the first brief) built the "
         "deterministic targets, margin tool, sourced GNSS file, verifier speed up, grid planner and "
         "reviewer pack, but its long runs were interrupted by a machine sleep and a WSL outage. The "
         "second night, reported here, finished them. Work ran under WSL on the owner's laptop with "
         "at most 4 workers and one heavy job at a time; `scripts/run_phase6_chain.sh` cached every "
         "unit and `scripts/watchdog_phase6.sh` can relaunch it.", "",
         "## Per stream (second night)", "",
         "### A. Housekeeping", "",
         "* The vendored three.js hash failed on Windows because git converted it to CRLF; "
         "`.gitattributes` now marks the vendored directories `-text`, so the files stay byte "
         "identical and the pinned hashes are unchanged.",
         "* The `/dev/zero` and named pipe checks moved to their own test, skipped with a reason where "
         "those special files do not exist; the other checks still run everywhere.",
         "* A third Windows only failure (`test_landed_drone_and_passer`) was an ill posed time "
         "assertion on a plateau of the distance; the test now checks that the reported time is a true "
         "minimiser, which is stricter about the value and holds on both platforms.",
         "* The ADEO brief names the Abu Dhabi Executive Office and states that no relationship "
         "exists.", "",
         "### B. Regeneration and sourced GNSS sensitivity", "",
         f"Fleet derived files still identical to phase 5 (stale): {stale_files()} "
         "(`docs/CHANGES.md` gives per file counts of what moved)."]
    if s0 and s1:
        for k in s1["oat"]:
            L.append(f"* {k}: P(violation) {f(s0['oat'][k]['baseline']['p'])} with the assumed bias, "
                     f"{f(s1['oat'][k]['baseline']['p'])} with the FAA derived bias.")
    L += [f"* P15: {prediction('P15')}.", "",
          "### C. Margin study", ""]
    if mg:
        for r in mg["rows"]:
            c = r["case"]
            lab = f"bias sigma {c['bias_sigma']} m" if "bias_sigma" in c else f"`{c['gnss_file']}`"
            L.append(f"* n = {c['n']}, {lab}: required nominal minimum separation "
                     f"{f(r['required_nominal_min_separation_m'])} m ({r['status']}).")
        L.append(f"Target Wilson upper bound {mg['target']}, {mg['trials']} trials per scale, "
                 f"seed {mg['seed']}. Simulated and model dependent (`docs/MARGIN.md`).")
    if ck:
        L.append("Command line cross check: `python -m sirb margin` reproduces the FAA case row "
                 + ("exactly." if ck["identical"] else f"except {ck['differing_keys']}."))
    L += [f"* P11: {prediction('P11')}.", "",
          "### D. Relative GNSS error", ""]
    if rel:
        st = rel["statistics"]
        L.append(f"One open source was found and read: {rel['source']['source_name']} "
                 f"({rel['source']['licence']}). Error after common mode cancellation over "
                 f"{st['baseline_km']} km: {f(st['relative_horizontal_mean_m'])} m mean horizontal, "
                 f"against {f(st['standalone_horizontal_mean_m'])} m standalone; per axis sigma "
                 f"{f(st['bias_sigma_m'])} m (`shows/gnss_relative_literature.json`). It is a "
                 "literature value for other hardware, so the flag stays `assumed: true`, and the "
                 "README now states that every stressed verdict hinges on this single unsourced "
                 "parameter.")
    L += ["", "### E. Mutation testing", ""]
    if mut and "phase6" in mut:
        L += ["| File | Mutants | Killed | Survived | Timeout | Not checked | Score |",
              "|---|---|---|---|---|---|---|"]
        for fn, d in sorted(mut["phase6"].items()):
            L.append(f"| `{fn}` | {d['total']} | {d['killed']} | {d['survived']} | {d['timeout']} | "
                     f"{d['not_checked']} | {100 * d['score']:.1f}% |")
        L.append("Fresh mutmut run on Linux (`phase6` section of `results/mutation.json`); "
                 "survivors and their classes are in `docs/MUTATION.md`.")
    else:
        L.append("**No fresh mutmut scores**: `results/mutation.json` has no `phase6` section.")
    L += ["", "### F. Differential report", ""]
    if pp and pl:
        L.append(f"The {pp['family']} family differs between platforms: Linux with Python "
                 f"{pl['a']['python']} and {pl['b']['python']} agree on every seed; Windows "
                 f"(Python {pp['b']['python']}) differs on {len(pp['seeds_differing'])} of "
                 f"{pp['seeds_compared']} seeds, {len(pp['seeds_with_different_disagreement_records'])} "
                 "of them in the disagreement records. With the same numpy version, eigenvalues are "
                 + ("identical" if pp["eigvals_identical"] else "not identical")
                 + " and matrix products "
                 + ("identical" if pp["matmul_identical"] else "not identical")
                 + " between the builds, so the cause is the LAPACK eigenvalue routine of the numpy "
                 "wheel (the companion matrix root finder), not the Python build and not Sirb code "
                 "(`results/platform_probe/`).")
    if dcmp:
        L.append(f"Linux rerun of the full report against the phase 5 copy, which was made on another "
                 f"machine with the same Python, numpy and scipy versions: {dcmp['changed']} changed "
                 f"values in {dcmp['compared']} compared (timing fields excluded), all in the "
                 "degenerate collision records and the largest gaps of that family; counts, verdict "
                 "counts and the brute force check are identical. The Linux run of this machine is now "
                 "the committed reference, and a second run reproduced it exactly.")
    else:
        L.append("The Linux rerun of the full report had not finished when this was generated.")
    L += ["", "### G. Reviewer pack", "",
          "Briefs, Arabic summary and README blocks regenerated from the result files by "
          "`scripts/make_briefs.py` and `scripts/make_results_doc.py`.", "",
          "### H. Hostile review", "",
          "A separate reviewer agent, given only the repository and the hard constraints, reported "
          "findings; the fixes and the rejected findings with reasons are in `docs/REVIEW_ROUNDS.md` "
          "(phase 6 section). Killing mutation survivors found one real defect: the baseline planner "
          "emitted zero length holds when nobody moved in a transition (fixed with a regression test; "
          "no committed plan was affected, and CI checks the plan hashes strictly).", "",
          "## Predictions, phase 6", ""]
    for n in ("P10", "P11", "P12", "P13", "P14", "P15", "P16"):
        L.append(f"* {n}: {prediction(n)}.")
    if idx:
        L += ["", "Fleet hashes committed: " + ", ".join(
            f"`{s['id']}` `{s['fleet_sha256'][:8]}`" for s in idx["shows"]) + "."]
    L += ["", "## Still unverified", "",
          "* Everything in the simulated layer remains model dependent; no flight data exists.",
          "* The relative GNSS bias between show drones has no measured value (stream D).",
          "* Equivalence arguments for surviving mutants are arguments, not proofs.",
          "* The Arabic summary has not been reviewed by a native speaker.",
          "* `results/viewer_bench.json` was not rerun after the target change (Playwright and "
          "Chromium were not available); its frame timings do not depend on exact positions.",
          "* The machine slept twice during the second night; every run resumed or was rerun from "
          "its cache, and no number depends on wall time except the labelled timing fields.", "",
          "## Exact steps for Huda", "",
          "1. Review pull request hudasol/sirb#1, then hudasol/sirb#2. Nothing is merged and no tag was "
          "pushed. Merge order: #1 first, then #2.",
          "2. Have `docs/SUMMARY_AR.md` reviewed by a native Arabic speaker.",
          "3. Decide on the licence proposal in `docs/LICENSE_PROPOSAL.md`.",
          "4. Decide whether any GNSS parameter should be marked as sourced; this branch keeps all "
          "of them assumed (`docs/GNSS_SOURCED.md`).",
          "5. Create the release and tags yourself after merging, if wanted.", ""]
    Path("docs/OVERNIGHT_REPORT.md").write_text("\n".join(L), encoding="utf-8")


if __name__ == "__main__":
    main()
