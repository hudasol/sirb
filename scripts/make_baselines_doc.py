"""Generate docs/BASELINES.md from results/baselines.json (no hand edited numbers)."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
d = json.loads((ROOT / "results" / "baselines.json").read_text())
cols = [("straight_labeled", "Straight lines, labeled"),
        ("waves_labeled", "sirb waves, labeled"),
        ("orca_r2.0_labeled", "ORCA r = 2.0 m"),
        ("orca_r2.4_labeled", "ORCA r = 2.4 m"),
        ("straight_unlabeled_hungarian", "Straight, free assignment")]


def cell(m):
    if m["status"] == "no_plan":
        return "no plan"
    flag = "pass" if m["pass"] else "FAIL"
    t = "" if m["status"] == "ok" else ", timeout"
    return f"{flag} {m['min_separation_m']:.2f} m, {m['makespan_s']:.1f} s{t}"


L = ["# Baseline comparison", "",
     "Generated by `scripts/make_baselines_doc.py` from `results/baselines.json` "
     "(`scripts/bench_baselines.py`, fixed seeds). Do not edit by hand.", "",
     f"Every plan is judged by the exact verifier against a {d['d_min_m']} m centre separation; "
     f"speed limit {d['vmax']} m/s. Each cell is: verdict, minimum separation, makespan. "
     "These are simulated results under the model, not flight evidence.", "",
     "| Scenario | " + " | ".join(c[1] for c in cols) + " |",
     "|---|" + "---|" * len(cols)]
for r in d["results"]:
    L.append(f"| {r['scenario']} | " + " | ".join(cell(r["methods"][k]) for k, _ in cols) + " |")
s = d["sampled_false_pass"]
L += ["", "## Sampled separation checking", "",
      f"{s['failing_fleets']} random two drone crossings that the exact verifier fails "
      f"(miss distance below {d['d_min_m']} m). Share that a frame sampled check at the same "
      "threshold passes anyway:", "", "| Frame step | False pass rate |", "|---|---|"]
for k, v in s["false_pass_rate"].items():
    L.append(f"| {k} s | {100 * v:.2f} % |")
L += ["", "Comparators: ORCA is a numpy reimplementation of the RVO2-3D algorithm "
      "(van den Berg et al., 2011), validated step for step against the Apache-2.0 reference "
      "implementation; see `docs/DATA_SOURCES.md`. Labeled means drone i must reach goal i; "
      "free assignment lets the exact Hungarian step choose.", ""]
(ROOT / "docs" / "BASELINES.md").write_text("\n".join(L))
