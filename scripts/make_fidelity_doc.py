"""Generate docs/MODEL_FIDELITY.md from results/fidelity.json (numbers are not typed by hand)."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
d = json.loads((ROOT / "results" / "fidelity.json").read_text())
dm, ra = d["delay_margin"], d["required_feedback_accel"]
DIVERGED = 50.0


def ci(r):
    lo, hi = r["p_violation_ci95"]
    return f"{r['p_violation']:.2f} ({lo:.2f} to {hi:.2f})"


def err(r):
    v = r["mean_max_tracking_error_m"]
    return f"diverged (above {DIVERGED:.0f} m)" if v > DIVERGED else f"{v:.2f}"


L = ["# Model fidelity: tracker latency and acceleration limit", "",
     "Generated by `scripts/make_fidelity_doc.py` from `results/fidelity.json` "
     "(`scripts/fidelity_study.py`). Do not edit by hand. Simulated results under assumed models; "
     "no flight data. Predictions P28 to P30 and their grading are in `docs/PREDICTIONS.md`.", "",
     "## What was added", "",
     "Two opt in options in the stress tracker (`StressConfig.latency_s` and `StressConfig.accel_limit`, "
     "`sirb.stress.track_limited`). The feedback acceleration is computed from the state `latency_s` "
     "earlier and its norm is capped at `accel_limit`; the wind drag acceleration is not capped. With "
     "both options off the original linear tracker is used and every earlier result is unchanged. "
     "Both values are ASSUMPTIONS: no vehicle datasheet figure for either was retrieved. A state "
     "estimator (Kalman style) was not built: it would add noise parameters with no data to set them.", "",
     "## Delay margin of the assumed loop", "",
     f"For the closed loop with natural frequency {2.0} rad/s and damping 0.9 the gain crossover is "
     f"{dm['crossover_rad_s']:.2f} rad/s, the phase margin {dm['phase_margin_deg']:.1f} degrees, and the delay "
     f"margin {dm['delay_margin_s']:.3f} s (computed by `delay_margin_s` in the study script). A feedback "
     "delay above that makes the loop unstable. The explicit discrete implementation behaves as if it had "
     f"about half a step more delay (step {d['dt']} s), so a latency of 0.3 s, which is below the continuous "
     "margin, already diverges in the simulation; this is consistent with 0.3 s plus half a step exceeding the margin.", "",
     "## Feedback acceleration the linear loop asks for", "",
     "Per drone peak of the feedback acceleration norm in the baseline tracker, over 20 trials "
     "(m/s^2). The mean wind drag acceleration in the wind case is shown for reference.", "",
     "| Case | Median peak | 95th percentile | Maximum | Mean wind drag accel |", "|---|---|---|---|---|"]
for case, a in ra.items():
    L.append(f"| {case} | {a['drone_peaks_p50']:.2f} | {a['drone_peaks_p95']:.2f} | "
             f"{a['drone_peaks_max']:.2f} | {a['wind_drag_accel_mean_m_s2']:.2f} |")
L += ["", "## Paired comparison", "",
      f"Show `{d['show']}`, {d['trials']} trials per cell, step {d['dt']} s, seed {d['seed']}, the same "
      "disturbance draws for every tracker model.", "",
      "| Case | Tracker | P(violation) (95% Wilson) | Median min separation (m) | Mean max tracking error (m) |",
      "|---|---|---|---|---|"]
for r in d["rows"]:
    L.append(f"| {r['case']} | {r['model']} | {ci(r)} | {r['min_separation_quantiles']['0.5']:.3f} | {err(r)} |")
L += ["", "## Do the conclusions move?", "",
      "The GNSS bias and comms loss conclusions do not move for a latency of 0.2 s or for caps of 2 and 4 "
      "m/s^2: the violation rates and median separations in the table agree with the baseline. The wind "
      "9 m/s conclusion does move. In the baseline it passes because the loop can cancel the drag; with a cap "
      "below the acceleration it needs (table above) the drag cannot be cancelled and the simulated drone "
      "drifts. The drag law uses the wind velocity, not the velocity relative to the air, so the size of that "
      "drift is not meaningful; the only conclusion is that this pass assumes the vehicle has feedback "
      "authority of roughly the table value. Any latency near or above the delay margin makes the result "
      "diverge for every case. Stress verdicts in this repository are therefore conditional on adequate "
      "control authority and on a feedback delay well below the margin; neither was measured on a vehicle.", ""]
(ROOT / "docs" / "MODEL_FIDELITY.md").write_text("\n".join(L))
