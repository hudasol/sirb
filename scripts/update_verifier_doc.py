"""Write the 'Differential verification' section of docs/VERIFIER.md and fill the P1 to P3
outcomes in docs/PREDICTIONS.md from results/differential.json (numbers are copied, not typed).

Usage: python scripts/update_verifier_doc.py
"""

from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BEGIN, END = "<!-- differential:begin -->", "<!-- differential:end -->"


def g(x: float) -> str:
    return f"{x:.3g}"


def section(d: dict) -> str:
    c, m, bf, vd = d["counts"], d["max_discrepancies"], d["brute_force"], d["verdicts"]
    nc = bf["near_collision_passes"]
    fam = ", ".join(f"{k} {v}" for k, v in c["adversarial_by_family"].items())
    groups: dict = {}
    for r in d["disagreements"]:
        key = (r["family"], r["kind"])
        gr = groups.setdefault(key, dict(n=0, worst=0.0, seeds=[], cause=r["diagnosis"]["cause"]))
        gr["n"] += 1
        gr["worst"] = max(gr["worst"], abs(r.get("diff", 0.0)))
        if len(gr["seeds"]) < 5:
            gr["seeds"].append(r["seed"])
    rows = "\n".join(
        f"| {f} | {k} | {v['n']} | {g(v['worst'])} | {v['seeds']} |"
        for (f, k), v in sorted(groups.items())) or "| none | | 0 | | |"
    causes = sorted({v["cause"].split(":")[0] for v in groups.values()})
    h = d["runtimes"]["hundred_drone_fleets"]
    fleets = {(r["family"], r["seed"]) for r in d["disagreements"]}
    refs = [r["diagnosis"].get("e_minus_reference") for r in d["disagreements"]
            if r["diagnosis"].get("e_minus_reference") is not None]
    kinds = sorted({r["kind"] for r in d["disagreements"]})
    n_c1 = sum(1 for r in d["disagreements"] if r["kind"].startswith(("C1", "C4")))
    if d["disagreements"]:
        findings = (
            f"{len(fleets)} fleets (all in the families "
            f"{', '.join(sorted({f for f, _ in fleets}))}) produced {len(d['disagreements'])} records of "
            f"kinds {kinds}; {n_c1} records violate C1 or C4, so verify2 never reported a lower "
            f"bound above the exact value and no verdict contradicted the exact value outside "
            f"1e-6 m. Cause (labelled by the extended precision reference): {', '.join(causes)}. "
            f"In these constructed collisions or near collisions, `|D|^2` has a root of high "
            f"multiplicity at the minimum, so the derivative has a root of multiplicity up to "
            f"2m-1; companion matrix eigenvalues of a multiple root carry an error of order "
            f"`eps^(1/(2m-1))`, Newton polishing converges only linearly there, and the best "
            f"candidate lands off the flat minimum. `sirb.verify` then reports a minimum that is "
            f"too large by up to {g(max(refs))} m (the reference value is the true minimum of "
            f"the float64 coefficients). This is above the 'about 1e-9' stated under Guarantees "
            f"and below the 1e-6 tolerance of the violation policy, so no verdict changes unless "
            f"a pair sits within that band of the threshold. It is float conditioning of root "
            f"finding, not a logic error: `sirb/verify.py` was not changed. A remedy, not applied "
            f"here, would be a bounded local minimisation of `|D|` around the best candidate.")
    else:
        findings = "No disagreement under criteria C1 to C4 in this run."
    return f"""{BEGIN}
## Differential verification

Generated by `scripts/differential_report.py` (results in `results/differential.json`) and
copied into this section by `scripts/update_verifier_doc.py`; the numbers below are not typed
by hand. Fixed seeds only; rerun with `PYTHONPATH=. python scripts/differential_report.py`.

**Second verifier (`sirb/verify2.py`).** It imports only the data classes of
`sirb.trajectory` and shares no code with `sirb/verify.py`; it uses no root finding. Pieces
(hold before, segments, hold after, gaps held) are paired when their time overlap has positive
length. For a pair of pieces on an overlap `[a, b]` the vector polynomial difference is
re-expanded by Horner synthetic division about a cell midpoint, its squared norm is formed
as a scalar polynomial in the local variable `r`, and a cell `[m - w, m + w]` gets the lower
bound `p0 + min(p1 r + p2 r^2) - sum_(k>=3) |p_k| w^k` (the quadratic part is minimised
exactly, the rest is bounded by absolute values), minus a rounding allowance of
`gamma * eps` times the magnitude of the terms (not directed rounding). The value at the
midpoint is an upper bound (a witnessed distance). Cells are bisected until their bound
reaches `best witness - tol` (`tol = 1e-9` m) or the cap; the result is a lower bound `l`, a
witness `u`, and the verdict at `d_min`: PASS only if `l >= d_min`, FAIL if a witnessed
distance (plus the allowance) is below `d_min`, otherwise UNDECIDED. A conservative box
prefilter (centred-form boxes per piece) discards piece pairs whose boxes are at least `cap`
apart. Cells still open at depth 48 would be reported as undecided leaves: there were
{m['n_undecided_leaves']} in this run.

**Agreement.** With `e` the exact minimum of `sirb.verify`, `l` and `u` the lower bound and
witness of `sirb.verify2`, per drone pair and overall:
C1 `l <= e + 1e-9`; C2 `e - l <= gap_bound + 1e-9`, where `gap_bound` is verify2's `tol`
plus its rounding allowance (the extra 1e-9 is the accuracy the exact verifier claims for
itself, because `e - l = (e - true) + (true - l)`); C3 `u >= e - 1e-9` (a witnessed distance
is a real distance and cannot beat the true minimum); C4 no PASS/FAIL contradiction outside
+/-1e-6 m of the threshold. A disagreement is any violated criterion, or a mismatch with the
analytic minimum of a constructed case by more than 1e-8 m.

**Counts.** {c['total_fleets']} fleets: {c['random_fleets']} random polynomial fleets (degree 1
to 5, 2 to 5 drones, 1 to 4 segments, some with jumps, gaps, overlaps), {c['adversarial_fleets']}
adversarial fleets ({fam}), {c['larger_fleets_12_drones']} fleets of 12 drones and
{c['hundred_drone_fleets']} fleets of 100 drones; {m['n_pairs_compared']} drone pairs compared
and {c['verdict_checks']} verdicts checked.

**Largest discrepancies.** `max (e - l)` = {g(m['max_e_minus_l'])} m; `max (l - e)` =
{g(m['max_l_minus_e'])} m (C1 limit 1e-9); `max (e - u)` = {g(m['max_e_minus_u_witness'])} m;
largest abs(exact - analytic construction) = {g(m['max_abs_e_minus_construction'])} m;
largest `gap_bound` = {g(m['max_gap_bound'])} m. Verdict counts: {vd.get('PASS', 0)} PASS,
{vd.get('FAIL', 0)} FAIL, {vd.get('UNDECIDED', 0)} UNDECIDED (largest abs(e - d_min) among
undecided: {g(vd.get('undecided_max_abs_e_minus_threshold', 0.0))} m); PASS with the exact
minimum below the threshold: {vd.get('pass_with_exact_below_threshold', 0)}; FAIL with the
exact minimum at or above the threshold: {vd.get('fail_with_exact_at_or_above_threshold', 0)}
(largest margin {g(vd.get('fail_with_exact_above_threshold_max_margin', 0.0))} m: these are
thresholds placed exactly at the exact minimum, where the witnessed distance can sit a few
rounding units below it).

**Disagreements ({c['n_disagreement_records']} records).** Every record, with seed, values and
a reference computation (extended precision grid scan plus zoom), is in
`results/differential.json`.

| family | kind | records | largest difference (m) | first seeds |
|---|---|---|---|---|
{rows}

**Findings.** {findings}

**Brute-force sampling** (`dt = 1e-4` s, windows of +/-0.05 s around the exact argmin and
around the coarse argmin, plus a coarse 1e-2 s global pass, plus the whole span when it is
at most 1 s): {bf['n_comparisons']} comparisons ({bf['n_single_segment_pairs']} random
single segment pairs, {bf['n_fleet_pairs']} pairs from random continuous multi segment fleets).
`max (sampled - exact)` = {g(bf['max_sampled_minus_exact'])} m; largest case where the sampled
value is below the exact minimum: {g(bf['max_negative_gap_exact_minus_sampled'])} m
({bf['n_sampled_below_exact_by_more_than_1e-9']} cases beyond 1e-9). Sampled minus exact
exceeded 1e-6 m in {bf['n_sampled_above_exact_by_more_than_1e-6']} cases, of which
{bf['n_above_1e-6_argmin_at_breakpoint']} had the exact argmin at a segment breakpoint (grid
points miss the kink by up to `v * dt / 2`) and
{bf['n_above_1e-6_argmin_not_at_breakpoint']} did not; with breakpoint times added to the
samples the largest `sampled - exact` is {g(bf['grid_plus_breakpoints_max_sampled_minus_exact'])} m.
The V shaped minima of {nc['n']} near collision passes: largest `sampled - exact`
{g(nc['max_sampled_minus_exact'])} m (sampling error bound `v*dt/2`).
verify2's lower bound exceeded a sampled distance by more than 1e-9 in
{bf['verify2_lower_bound_above_sampled_by_more_than_1e-9']} cases.

**Timing.** 100 drone fleets: verify2 {g(min(r['verify2_s'] for r in h))} to
{g(max(r['verify2_s'] for r in h))} s, `sirb.verify` {g(min(r['verify_s'] for r in h))} to
{g(max(r['verify_s'] for r in h))} s. Whole report: {g(d['runtimes']['total_s'])} s.

**Limits.** The lower bound is rigorous in exact arithmetic; in floating point it is
rigorous up to an explicit allowance (`gamma * eps` times term magnitudes), not directed
rounding, so it is not a formal proof. Both verifiers read the float64 coefficients as exact
and share the modelling choices (hold before and after, gaps held, later segment wins in an
overlap, drones as points); the differential test cannot find an error in those shared
choices, and the two programs have one author. Pieces are paired only when their overlap has
positive length, so for a trajectory with a position jump the mixed instant (end of one piece,
start of another) is not examined by either verifier. The cases are generated by the
families in `sirb/diffcases.py`; other structures could behave differently. Fleets are small
(2 to 12 drones; 100 only for timing and bound checks). Degrees above 5 appear only in the
long high degree family (up to 7). The reference used for diagnosis is a sampled
extended precision search, not a proof. Dynamics, structure and geometry checks are not
covered by this comparison.
{END}
"""


def predictions(d: dict) -> dict:
    c, bf, vd = d["counts"], d["brute_force"], d["verdicts"]
    n4 = sum(1 for r in d["disagreements"] if r["kind"].startswith("C4"))
    miss_p3 = bf["max_sampled_minus_exact"] >= 1e-6
    return {
        "P1": (f"{c['total_fleets']} fleets, {c['verdict_checks']} verdict checks: "
               f"{n4} PASS/FAIL contradictions outside 1e-6 m; "
               f"{vd.get('pass_with_exact_below_threshold', 0)} PASS with exact below threshold "
               f"(results/differential.json)",
               "Hit" if n4 == 0 and vd.get("pass_with_exact_below_threshold", 0) == 0
               else "Miss"),
        "P2": (f"verify2 never reports extra FAILs (FAIL needs a witnessed distance below the "
               f"threshold); near threshold it returns UNDECIDED: {vd.get('UNDECIDED', 0)} cases, "
               f"all with abs(e - d_min) <= "
               f"{g(vd.get('undecided_max_abs_e_minus_threshold', 0.0))} m; "
               f"FAIL with exact at or above threshold: "
               f"{vd.get('fail_with_exact_at_or_above_threshold', 0)}",
               "Hit (conservatism appears as UNDECIDED, not as extra violations)"),
        "P3": (f"sampled minus exact: max {g(bf['max_sampled_minus_exact'])} m on the plain "
               f"grid ({bf['n_above_1e-6_argmin_at_breakpoint']} of "
               f"{bf['n_sampled_above_exact_by_more_than_1e-6']} cases above 1e-6 have the argmin "
               f"at a breakpoint), {g(bf['grid_plus_breakpoints_max_sampled_minus_exact'])} m "
               f"with breakpoints added; sampled below exact: max "
               f"{g(bf['max_negative_gap_exact_minus_sampled'])} m",
               "Miss as stated (plain grid), hit with breakpoints added" if miss_p3 else "Hit"),
    }


def main():
    d = json.loads((ROOT / "results" / "differential.json").read_text())
    doc = ROOT / "docs" / "VERIFIER.md"
    text = doc.read_text()
    new = section(d)
    if BEGIN in text:
        text = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?", lambda _: new, text,
                      flags=re.S)
    else:
        text = text.rstrip("\n") + "\n\n" + new
    doc.write_text(text)
    pp = ROOT / "docs" / "PREDICTIONS.md"
    lines = pp.read_text().split("\n")
    pred = predictions(d)
    for i, ln in enumerate(lines):
        for key, (outcome, hit) in pred.items():
            if ln.startswith(f"| {key} |"):
                cells = ln.split(" | ")
                # columns: id | prediction | outcome | hit
                prediction = " | ".join(cells[:-2]).rstrip()
                lines[i] = f"{prediction} | {outcome} | {hit} |"
    pp.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
