"""Generate docs/GNSS_SOURCED.md from results/gnss_faa_derivation.json, results/sensitivity.json,
results/sensitivity_faa.json and (if present) results/margin.json. No hand typed numbers."""

from __future__ import annotations

import json
from pathlib import Path


def load(p):
    p = Path(p)
    return json.loads(p.read_text()) if p.exists() else None


def f(x, n=3):
    return "n/a" if x is None else f"{x:.{n}f}"


def crossing(d):
    """Parameters whose low or high value lies on the other side of P = 0.05 from the baseline."""
    b = d["baseline"]["p"] > 0.05
    return sorted(p for p, v in d["params"].items()
                  if (v["low"]["p"] > 0.05) != b or (v["high"]["p"] > 0.05) != b)


def main() -> None:
    D = load("results/gnss_faa_derivation.json")
    S0 = load("results/sensitivity.json")
    S1 = load("results/sensitivity_faa.json")
    M = load("results/margin.json")
    st, src = D["statistics"], D["source"]
    L = ["# Sourced GNSS parameters (stream B, phase 6)", "",
         "Generated by `scripts/make_gnss_sourced_doc.py` from `results/gnss_faa_derivation.json`, "
         "`results/sensitivity.json`, `results/sensitivity_faa.json` and `results/margin.json`. "
         "Everything below the source table is **simulated**: a property of the model with the "
         "stated parameters, not of real aircraft.", "",
         "## Source", "",
         f"* {src['source_name']}: <{src['url']}>, retrieved {src['retrieval_date']}.",
         f"* Licence: {src['licence']}. The extracted table is kept in "
         "`data/faa_sps_pan131_table5_2.csv` with the SHA-256 of the report.",
         "* What it measures: the 95% horizontal and vertical position error of single frequency GPS "
         "(SPS) at fixed WAAS reference sites over each 24 hour period, against surveyed positions.",
         "", "## What the source supports, and what it does not", "",
         "* It supports the magnitude of the **absolute** error of one standalone receiver, that is a "
         "drone that has lost its RTK corrections and falls back to plain GPS.",
         "* Sirb's model applies the bias **independently** to each degraded drone, so the separation "
         "it erodes is the **relative** error between two drones. Nearby receivers that track the same "
         "satellites share most of their error (orbit, clock, ionosphere, troposphere), so the "
         "relative error is expected to be smaller than the absolute one. No retrieved source gives "
         "it. Using the absolute figure for the relative one is a judgement, so **every value in "
         "`shows/gnss_faa_sps_standalone.json` stays `assumed: true`**, following the rule in "
         "`docs/GNSS_PARAMS.md`. No usable public source for the relative error was found.",
         "* The degraded fraction (0.25), correlation time, white noise and dropout values have no "
         "source here; they are the scenario values and defaults.",
         "* `hudasol/marsad` and the Tashwish project publish no position error statistics that this "
         "format can use (`docs/GNSS_PARAMS.md`); nothing from them is used.", "",
         "## Derivation", "",
         "Per axis sigma of a circular Gaussian whose 95% horizontal radius is R95: sigma = R95 / "
         f"{f(st['k_h95'], 4)}. Vertical (one dimension): sigma_z = V95 / {f(st['k_v95'], 4)}.", "",
         "| Quantity | Value |", "|---|---|",
         f"| sites in the table | {st['n_sites']} |",
         f"| median 95% horizontal error | {f(st['h95_median_m'])} m |",
         f"| site range of 95% horizontal error | {f(st['h95_min_m'])} to {f(st['h95_max_m'])} m |",
         f"| per axis sigma, median site (used) | {f(st['bias_sigma_median_m'])} m |",
         f"| per axis sigma, site range (sensitivity range) | {f(st['bias_sigma_min_site_m'])} to "
         f"{f(st['bias_sigma_max_site_m'])} m |",
         f"| vertical sigma, median site (reported, not used: the model has one sigma) | "
         f"{f(st['vertical_sigma_median_m'])} m |", ""]
    if S0 and S1:
        L += ["## Sensitivity study rerun with the sourced value", "",
              f"Assumed scenario (phase 5): {S0['scenario']}. Sourced scenario: bias sigma "
              f"{S1['scenario']['gnss_bias_sigma']} m, other values as listed in the file, mean wind "
              f"{S1['scenario']['w20']} m/s. Bias sigma range in the sourced run: the site range. "
              f"{S1['trials_oat']} trials per configuration, common random numbers.", "",
              "| Baseline | Scenario | P(violation) | 95% CI | Median min sep (m) | Top 3 by swing "
              "| Parameters crossing P = 0.05 |", "|---|---|---|---|---|---|---|"]
        for name in S0["oat"]:
            for lab, S in (("assumed", S0), ("sourced", S1)):
                d = S["oat"][name]
                b = d["baseline"]
                top = ", ".join(r["param"] for r in S["ranking_by_swing"][name][:3])
                L.append(f"| {name} | {lab} | {f(b['p'])} | {f(b['ci'][0])} to {f(b['ci'][1])} | "
                         f"{f(b['median_min_sep'])} | {top} | {', '.join(crossing(d)) or 'none'} |")
        L += ["", "Swing of bias sigma over its range (median minimum separation, metres):", "",
              "| Baseline | Assumed range | Swing | Sourced range | Swing |", "|---|---|---|---|---|"]
        for name in S0["oat"]:
            r0 = next(r for r in S0["ranking_by_swing"][name] if r["param"] == "gnss_bias_sigma")
            r1 = next(r for r in S1["ranking_by_swing"][name] if r["param"] == "gnss_bias_sigma")
            a, b = S0["ranges"]["gnss_bias_sigma"], S1["ranges"]["gnss_bias_sigma"]
            L.append(f"| {name} | {f(a[0])} to {f(a[2])} | {f(r0['swing_m'])} | {f(b[0])} to "
                     f"{f(b[2])} | {f(r1['swing_m'])} |")
        L += ["", "## Which conclusions change", ""]
        for name in S0["oat"]:
            p0, p1 = S0["oat"][name]["baseline"]["p"], S1["oat"][name]["baseline"]["p"]
            side = lambda p: "above" if p > 0.05 else "at or below"  # noqa: E731
            change = "changes" if (p0 > 0.05) != (p1 > 0.05) else "does not change"
            L.append(f"* {name}: P(violation) {f(p0)} with the assumed sigma, {f(p1)} with the "
                     f"sourced sigma; the verdict relative to 5% {change} ({side(p0)} to {side(p1)}).")
        for name in S0["oat"]:
            t0 = [r["param"] for r in S0["ranking_by_swing"][name][:2]]
            t1 = [r["param"] for r in S1["ranking_by_swing"][name][:2]]
            L.append(f"* {name}: the first two parameters by swing are {', '.join(t0)} (assumed) and "
                     f"{', '.join(t1)} (sourced); the ranking {'survives' if t0 == t1 else 'changes'}.")
    if M:
        rows = [r for r in M["rows"] if "gnss_file" in r["case"]]
        for r in rows:
            L += ["", "## Separation needed with the sourced file (margin synthesis)", "",
                  f"Case {r['case']}: status `{r['status']}`, required nominal minimum separation "
                  f"{f(r['required_nominal_min_separation_m'])} m (formation spacing "
                  f"{f(r['required_spacing_m'], 2)} m), target Wilson upper bound {M['target']} over "
                  f"{M['trials']} trials. {M['model_dependence']}"]
    R = load("results/gnss_relative_derivation.json")
    if R:
        rs = R["statistics"]
        L += ["", "## Relative error between drones (stream D)", "",
              f"* Source read: {R['source']['source_name']}, <{R['source']['url']}>, licence "
              f"{R['source']['licence']}, retrieved {R['source']['retrieval_date']}. The table used is "
              "kept in `data/carvalho2023_sensors_table1.csv`.",
              f"* In one 800 s run a low cost receiver on a moving rover had a mean horizontal error of "
              f"{f(rs['standalone_horizontal_mean_m'])} m standalone and {f(rs['relative_horizontal_mean_m'])} m "
              f"after pseudorange differencing against a reference station {rs['baseline_km']} km away, "
              f"which cancels the errors common to both sites (ratio {f(rs['relative_over_standalone'], 2)}).",
              f"* Mapped to a per axis sigma for a circular Gaussian (mean radius / {f(rs['k_rayleigh_mean'], 4)}): "
              f"{f(rs['bias_sigma_m'])} m, written to `shows/gnss_relative_literature.json`.",
              "* This is a **literature value, not a measurement of the target hardware**: one receiver "
              "type, one run, a high grade reference instead of a second low cost receiver, tree canopy, "
              "a Kalman filter, GPS L1 only. The mapping and the setting are judgements, so the flag "
              "stays `assumed: true`. No source was found that measures the error between two nearby "
              "low cost receivers without corrections, which is the quantity the model uses.",
              "* Consequence: **the stressed verdict hinges on this single unsourced parameter**. Over "
              "the values discussed here (the literature anchored value above, the FAA absolute range, "
              "and the assumed sweep in `docs/SENSITIVITY.md`) the required separation changes by "
              "metres (`docs/MARGIN.md`)."]
    L += ["", "## Limits", "",
          "The model's GNSS errors are independent between drones; real standalone errors are largely "
          "common to nearby drones, so these sourced runs are expected to overstate relative error. "
          "A fleet wide common error (for example jamming or spoofing) is not modelled at all "
          "(`docs/HAZARDS.md`). The reference sites are in the United States, Canada and Mexico, not in the UAE."]
    Path("docs/GNSS_SOURCED.md").write_text("\n".join(L) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
