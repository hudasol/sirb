"""Generate docs/CHANGES.md: which published results moved in phase 6, and by how much.

Every number is computed by comparing the result files on the phase 5 branch head (REF, read
with ``git show``) with the files in the working tree. Wall clock fields are ignored. A file in
FLEET_DERIVED that is byte identical to its phase 5 version is listed as stale, because the
deterministic target change of stream E alters every planned fleet.

    python scripts/make_changes_doc.py
"""

from __future__ import annotations

import json
import re
import subprocess
from pathlib import Path

REF = "4d1d480"   # head of phase5-hardening when phase 6 started
TIMING = re.compile(r"(_s|_cpu_s|runtime_s|wall_s|_ms|peak_rss_mb|cum_s)$")
FLEET_DERIVED = {
    "results/planners.json": "scripts/bench_planners.py",
    "results/assignment.json": "scripts/bench_planners.py",
    "results/stress_sweeps.json": "scripts/run_stress.py sweeps",
    "results/stress_spacing.json": "scripts/run_stress.py spacing",
    "results/stress_contingency.json": "scripts/run_stress.py contingency",
    "results/stress_scaling.json": "scripts/run_stress.py scaling",
    "results/sensitivity.json": "scripts/sensitivity.py",
    "results/scaling_profile.json": "scripts/profile_scale.py",
    "results/ground_robots.json": "scripts/ground_robots.py",
    "viewer/data/index.json": "scripts/build_viewer_data.py",
    "results/viewer_bench.json": "scripts/viewer_bench.py (needs Playwright and Chromium)",
}
OTHER = {"results/differential.json": "scripts/differential_report.py (random and adversarial "
         "fleets, not planned shows)"}


def old(path):
    p = subprocess.run(["git", "show", f"{REF}:{path}"], capture_output=True, text=True)
    return json.loads(p.stdout) if p.returncode == 0 else None


def leaves(o, path=""):
    if isinstance(o, dict):
        for k, v in o.items():
            yield from leaves(v, f"{path}.{k}")
    elif isinstance(o, list):
        for i, v in enumerate(o):
            yield from leaves(v, f"{path}[{i}]")
    else:
        yield path, o


def compare(a, b):
    la = {k: v for k, v in leaves(a) if not TIMING.search(k.split(".")[-1].split("[")[0])}
    lb = {k: v for k, v in leaves(b) if not TIMING.search(k.split(".")[-1].split("[")[0])}
    changed = [k for k in la.keys() & lb.keys() if la[k] != lb[k]]
    num = [abs(lb[k] - la[k]) for k in changed
           if isinstance(la[k], (int, float)) and isinstance(lb[k], (int, float))
           and not isinstance(la[k], bool)]

    def maxd(pat):
        d = [abs(lb[k] - la[k]) for k in changed if re.search(pat, k)
             and isinstance(la[k], (int, float)) and not isinstance(la[k], bool)]
        return max(d) if d else 0.0
    inside = total = 0
    for k in changed:
        if k.endswith(".p_violation") and f"{k}_ci95[0]" in la:
            total += 1
            inside += la[f"{k}_ci95[0]"] <= lb[k] <= la[f"{k}_ci95[1]"]
    return {"compared": len(la.keys() & lb.keys()), "changed": len(changed),
            "p_inside_old_ci": inside, "p_changed": total,
            "only_old": len(la.keys() - lb.keys()), "only_new": len(lb.keys() - la.keys()),
            "max_p": maxd(r"p_violation$|\.p$"), "max_sep": maxd(r"min_separation|min_sep|min_nn"),
            "max_any": max(num) if num else 0.0}


def main() -> None:
    L = ["# Changes that move published numbers", "",
         "Generated by `scripts/make_changes_doc.py`, which compares each result file with its "
         f"version on the phase 5 branch head (`{REF}`); wall clock fields are ignored.", "",
         "## Phase 6, stream E: deterministic targets and exact assignment costs", "",
         "What changed: `sirb.shapes.generate_points` snaps every target to a 2^-20 m grid; "
         "`sirb.assign` computes Hungarian costs as exact integers on that grid; "
         "`sirb.planner.common` builds legs with products and `math.sqrt` instead of BLAS and "
         "`pow`. Reason and evidence: `docs/REPRODUCIBILITY.md`. Targets move by at most half a grid "
         "cell per coordinate, leg coefficients change in the last bits, and tied assignments of "
         "grid and text shapes may resolve to another member of the tie, which can change a plan "
         "substantially while keeping its total cost. Every fleet hash changed. All files below were "
         "regenerated on Linux by `scripts/run_phase6_chain.sh` (or the script named), with the same "
         "seeds and trial counts as before.", "",
         "| File | Script | Status | Leaves compared | Changed | Largest change in P(violation) "
         "| Changed P(violation) inside the old 95% interval | Largest change in a separation (m) |",
         "|---|---|---|---|---|---|---|---|"]
    stale = []
    for path, script in {**FLEET_DERIVED, **OTHER}.items():
        a = old(path)
        p = Path(path)
        if a is None or not p.exists():
            L.append(f"| `{path}` | {script} | new in phase 6 or missing | | | | | |")
            continue
        b = json.loads(p.read_text(encoding="utf-8"))
        c = compare(a, b)
        same = c["changed"] == 0 and c["only_old"] == 0 and c["only_new"] == 0
        status = "unchanged" if same else "regenerated"
        if same and path in FLEET_DERIVED:
            status = "**stale (identical to phase 5)**"
            stale.append(path)
        if c["only_old"] or c["only_new"]:
            L.append(f"| `{path}` | {script} | regenerated; rows were added or removed, so a leaf by "
                     f"leaf comparison is not meaningful ({c['only_new']} new leaves, {c['only_old']} "
                     "removed) | | | | | |")
            continue
        L.append(f"| `{path}` | {script} | {status} | {c['compared']} | {c['changed']} | "
                 f"{c['max_p']:.3g} | {c['p_inside_old_ci']} of {c['p_changed']} | "
                 f"{c['max_sep']:.3g} |")
    L += ["", "Stale files (fleet derived but identical to phase 5): "
          + (", ".join(f"`{s}`" for s in stale) if stale else "none") + ".", "",
          "Differences in P(violation) come from Monte Carlo runs with the same seeds on plans that "
          "changed; the column above counts how many changed estimates still lie inside the 95% "
          "Wilson interval reported in phase 5 (only rows that carry an interval are counted).", ""]
    Path("docs/CHANGES.md").write_text("\n".join(L), encoding="utf-8")


if __name__ == "__main__":
    main()
