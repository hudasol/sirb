"""How the stressed verdict depends on how much of the GNSS bias is common to all drones.

Uses the sourced FAA absolute error scale (shows/gnss_faa_sps_standalone.json) with every drone
degraded, the 100 drone demo show, 100 trials per row, fixed seed. Writes results/gnss_common.json
and docs/GNSS_COMMON.md.
"""

import json
from pathlib import Path

from sirb.disturbance import StressConfig
from sirb.gnss_params import load, to_stress_config
from sirb.planner.baseline import plan_baseline
from sirb.spec import load_show
from sirb.stress import monte_carlo, sample_reference

ROOT = Path(__file__).resolve().parents[1]
TRIALS, SEED = 100, 20261028
FRACTIONS = [0.0, 0.5, 0.9, 0.95, 0.99, 1.0]


def main() -> None:
    show = load_show(ROOT / "shows" / "sirb_text_100.json")
    fleet, _ = plan_baseline(show)
    base = to_stress_config(load(ROOT / "shows" / "gnss_faa_sps_standalone.json"),
                            base=StressConfig(dt=0.2)).with_(gnss_deg_fraction=1.0)
    ref = sample_reference(fleet, base.dt)
    d_min = show["limits"]["min_separation_m"]
    rows = []
    for c in FRACTIONS:
        r = monte_carlo(ref, base.with_(gnss_common_fraction=c), d_min, TRIALS, SEED)
        rows.append({"common_fraction": c, "p_violation": r["p_violation"],
                     "p_violation_ci95": r["p_violation_ci95"],
                     "median_min_separation_m": r["min_separation_quantiles"]["0.5"]})
        print(rows[-1], flush=True)
    out = {"show": show["name"], "d_min_m": d_min, "trials": TRIALS, "seed": SEED,
           "bias_sigma_m": base.gnss_bias_sigma, "degraded_fraction": 1.0, "rows": rows}
    (ROOT / "results" / "gnss_common.json").write_text(json.dumps(out, indent=1))
    L = ["# GNSS error correlation between drones", "",
         "Generated by `scripts/gnss_common_study.py` from `results/gnss_common.json`. "
         "Simulated under assumed models.", "",
         f"Show: {out['show']}; every drone degraded; per axis bias sigma {out['bias_sigma_m']} m "
         "(the sourced absolute error scale of `docs/GNSS_SOURCED.md`); "
         f"{TRIALS} trials per row; separation threshold {d_min} m. The common fraction is the "
         "share of the bias variance shared by all drones (`--gnss-common-fraction`).", "",
         "| Common fraction | P(violation) | Wilson 95% | Median minimum separation (m) |",
         "|---|---|---|---|"]
    for r in rows:
        lo, hi = r["p_violation_ci95"]
        L.append(f"| {r['common_fraction']} | {r['p_violation']:.3f} | {lo:.3f} to {hi:.3f} | "
                 f"{r['median_min_separation_m']:.3f} |")
    L += ["", "The verdict is governed by how correlated nearby drones' errors are, not by the "
          "size of the absolute error. No retrieved source gives that correlation for the "
          "receivers used in a show, so stressed verdicts stay labelled as depending on an "
          "unsourced assumption. This study does not claim that any particular fraction applies "
          "to a real receiver set.", ""]
    (ROOT / "docs" / "GNSS_COMMON.md").write_text("\n".join(L))


if __name__ == "__main__":
    main()
