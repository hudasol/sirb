"""Generate docs/BENCHMARK_V2.md from results/benchmark_v2.json (no hand edited numbers)."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
d = json.loads((ROOT / "results" / "benchmark_v2.json").read_text())
S = d["strata"]
names = [("gross", "Gross violation (miss 0 to 0.5 x threshold)"),
         ("shallow", "Shallow violation (0.5 to 0.99 x)"),
         ("safe", "Safe control (1.01 to 1.5 x)"),
         ("razor_violating", "Razor violation (depth 1e-6 to 1e-4 m)"),
         ("razor_safe", "Razor safe (margin 1e-6 to 1e-4 m)")]


def pc(r):
    lo, hi = r["ci95"]
    return f"{r['count']}/{r['n']} ({100 * r['rate']:.1f}%, {100 * lo:.1f} to {100 * hi:.1f})"


L = ["# Detection benchmark", "",
     "Generated by `scripts/make_benchmark_v2_doc.py` from `results/benchmark_v2.json` "
     "(`scripts/bench_detection.py`, seed " + str(d["seed"]) + "). Do not edit by hand. "
     "Simulated cases; timings are of this repository's Python implementations on one 2 core "
     "machine and do not transfer to other implementations.", "",
     f"Threshold {d['d_min_m']} m centre to centre. Truth for the crossing strata is the analytic "
     "miss distance of the constructed straight line flights; truth for the razor strata is the "
     "analytic value built into `sirb/diffcases.py`. Neither comes from the verifier under test. "
     "Cells show the number of WRONG verdicts (a violating case judged pass, or a safe case judged "
     "violating), with the Wilson 95% interval in percent; the undecided column counts cases the interval verifier did not decide.", "",
     "## Wrong verdicts", "",
     "| Stratum | n | Exact | Interval | Interval undecided | Sampled 0.5 s | 0.2 s | 0.1 s | "
     "0.05 s | 0.01 s | Sampled at matched time |",
     "|---|---|---|---|---|---|---|---|---|---|---|"]
for key, label in names:
    v = S[key]
    L.append(f"| {label} | {v['n']} | {pc(v['exact_wrong'])} | {pc(v['interval_wrong'])} | "
             f"{pc(v['interval_undecided'])} | " +
             " | ".join(pc(v["fixed_wrong"][k]) for k in ("0.5", "0.2", "0.1", "0.05", "0.01")) +
             f" | {pc(v['matched_wrong'])} |")
L += ["", "Sampled at matched time: the dense sampler given the same wall clock time that the "
      "exact verifier took on the same fleet. Its median frame step per stratum:", "",
      "| Stratum | Median matched frame step (s) | Median exact time (ms) | Median interval time (ms) |",
      "|---|---|---|---|"]
for key, label in names:
    v = S[key]
    L.append(f"| {label} | {v['matched_dt_median']:.4f} | {1e3 * v['median_exact_s']:.2f} | "
             f"{1e3 * v['median_interval_s']:.2f} |")
L += ["", "## Fleet size sweep", "",
      "Random straight line fleets, 7 repeats per cell; cv is the coefficient of variation. "
      "The pair search radius was 1000 m, so no pair was pruned (pairs examined equals total pairs).",
      "", "| Drones | Exact median (ms) | Exact cv | Pairs | Sampled 0.1 s (ms) | 0.05 s (ms) | "
      "0.01 s (ms) |", "|---|---|---|---|---|---|---|"]
for n, v in d["size_sweep"].items():
    sp = v["sampled"]
    L.append(f"| {n} | {1e3 * v['exact_median_s']:.2f} | {v['exact_cv']:.2f} | {v['pairs_examined']} | "
             + " | ".join(f"{1e3 * sp[k]['median_s']:.2f}" for k in ("0.1", "0.05", "0.01")) + " |")
L += ["", "## How to read this", "",
      "The exact and interval verifiers made no wrong verdict in any stratum. A sampled check "
      "matches them on gross and safe cases at every frame step tested, loses a small share of "
      "shallow violations at 0.5 s and 0.2 s, and misses most razor thin violations at every "
      "step, because a frame has to land within the violation depth of the closest approach. "
      "At the same wall clock time the sampler's step is finer than 0.03 s, and there it "
      "catches every shallow violation. The practical advantage of the exact verifier on these "
      "sets is therefore the guarantee at any depth, not a detection gain on violations deep "
      "enough to matter. Whether a 0.1 mm violation matters is a modelling question: the tracking "
      "error of a real vehicle is far larger.", ""]
(ROOT / "docs" / "BENCHMARK_V2.md").write_text("\n".join(L))
